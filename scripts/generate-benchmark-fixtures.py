#!/usr/bin/env python3
"""Embed existing AVIF inputs and independent RGBA16 references for benchmarks."""

import argparse
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'tests/fixtures'
OUTPUT = ROOT / 'benchmarks/fixtures.mbt'
CASES = [
    ('nclx709_422_10bit_2x2_odd_crop', True),
    ('nclx709_444_12bit_2x2_odd_crop', True),
    ('alpha_grid_grid_12bit', True),
    ('animation_matrix6_12bit', True),
    ('mono_12bit', False),
    ('ictcp_pq_444_10bit', False),
    ('ictcp_hlg_444_12bit', False),
]


def generate():
    spec = importlib.util.spec_from_file_location(
        'benchmark_embed', Path(__file__).with_name('generate-native-api-tests.py'))
    embed = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(embed)
    # Reuse only the lossless byte/RLE readers, not any decoder or color math.
    helpers = embed.HELPERS[embed.HELPERS.index('///|'):]
    helpers = helpers[:helpers.index('///|\nfn native_test_frame')]
    cases = {c['name']: c for c in json.loads(
        (FIXTURES / 'rgba16/manifest.json').read_text(encoding='utf-8'))['cases']}
    result = ['/// Generated by scripts/generate-benchmark-fixtures.py.\n'
              '/// Inputs and references retain tests/fixtures/rgba16 provenance.\n', helpers,
              '///|\nfn fixtures() -> Array[Fixture] {\n[']
    for name, decode in CASES:
        case = cases[name]
        references = ',\n'.join(embed.reference_expr(embed.samples(
            FIXTURES / 'rgba16' / frame['output'], 16)) for frame in case['frames'])
        result.append(f'''{{ name: "{name}",
            input: {embed.input_expr(FIXTURES / case['source'])},
            width: {case['width']}, height: {case['height']},
            references: [{references}], decode: {str(decode).lower()} }},''')
    result.append(']\n}\n')
    return subprocess.run(['moonfmt', '-'], input='\n'.join(result),
                          text=True, encoding='utf-8', capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
            raise SystemExit('Benchmark fixtures are stale; run the generator without --check')
        print(f'Benchmark fixtures checked: {len(CASES)} unchanged inputs/reference sets')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
        print(f'Generated {OUTPUT.relative_to(ROOT)} from {len(CASES)} existing fixture sets')


if __name__ == '__main__':
    main()
