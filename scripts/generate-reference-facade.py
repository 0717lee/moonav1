#!/usr/bin/env python3
"""Regenerate the public test facade for tests/reference.

MoonBit packages are directory-scoped. The generated reference suites are
black-box tests, so they can live in their own package, but they were written
against the root package's test-import-all surface. This facade re-exports the
root public API inside the reference package so those bodies stay unchanged.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_API = ROOT / "pkg.generated.mbti"
OUTPUT = ROOT / "tests/reference/facade.mbt"


def declarations() -> tuple[list[str], list[str]]:
    types: set[str] = set()
    values: set[str] = set()
    pattern = re.compile(
        r"^pub(?:\([^)]*\))?\s+(fn|let|const|struct|enum)\s+([A-Za-z_][A-Za-z0-9_]*)"
    )
    method = re.compile(r"^pub fn\s+[A-Za-z_][A-Za-z0-9_]*::")
    for raw in PUBLIC_API.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        match = pattern.match(line)
        if not match:
            continue
        kind, name = match.groups()
        if kind == "fn":
            if method.match(line):
                continue
            values.add(name)
        elif kind in ("let", "const"):
            values.add(name)
        else:
            types.add(name)
    return sorted(types), sorted(values)


def render() -> str:
    types, values = declarations()
    lines = [
        "// Generated by scripts/generate-reference-facade.py. Do not edit.",
        "/// Test-only facade for generated black-box reference suites.",
        "///",
        "/// Re-export the root public surface so moved reference cases stay readable",
        "/// without rewriting generated bodies.",
        "pub using @moonav1 {",
    ]
    lines.extend(f"  type {name}," for name in types)
    lines.extend(f"  {name}," for name in values)
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is stale")
        print(f"OK {OUTPUT.relative_to(ROOT)}")
        return
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"WROTE {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
